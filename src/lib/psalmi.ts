/**
 * Псалтир у богослужењу користи нумерацију Септуагинте (LXX), а Даничићев превод хебрејску.
 * Нпр. покајни псалам је 50. по LXX, а 51. код Даничића.
 */
export function lxxUHebrejski(n: number): number {
  if (n <= 9) return n;
  if (n <= 112) return n + 1;
  if (n === 113) return 114;
  if (n <= 115) return 116;
  if (n <= 145) return n + 1;
  if (n <= 147) return 147;
  return n;
}

