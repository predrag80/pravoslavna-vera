/** Ћирилица → латиница (српска абецеда). Садржај се чува на ћирилици, латиница се добија пресловљавањем. */
const MAPA: Record<string, string> = {
  А: 'A', Б: 'B', В: 'V', Г: 'G', Д: 'D', Ђ: 'Đ', Е: 'E', Ж: 'Ž', З: 'Z', И: 'I', Ј: 'J', К: 'K', Л: 'L', Љ: 'Lj',
  М: 'M', Н: 'N', Њ: 'Nj', О: 'O', П: 'P', Р: 'R', С: 'S', Т: 'T', Ћ: 'Ć', У: 'U', Ф: 'F', Х: 'H', Ц: 'C', Ч: 'Č',
  Џ: 'Dž', Ш: 'Š',
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', ђ: 'đ', е: 'e', ж: 'ž', з: 'z', и: 'i', ј: 'j', к: 'k', л: 'l', љ: 'lj',
  м: 'm', н: 'n', њ: 'nj', о: 'o', п: 'p', р: 'r', с: 's', т: 't', ћ: 'ć', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'č',
  џ: 'dž', ш: 'š',
};
const DVOSLOVNA = /[ЉЊЏ](?=[А-ЯЂЈЉЊЋЏ])/g;

export function uLatinicu(tekst: string): string {
  // „ЉУБОСТИЊА“ → „LJUBOSTINJA“, а „Љубостиња“ → „Ljubostinja“.
  const sredjen = tekst.replace(DVOSLOVNA, (s) => ({ Љ: 'LJ', Њ: 'NJ', Џ: 'DŽ' })[s] ?? s);
  let izlaz = '';
  for (const z of sredjen) izlaz += MAPA[z] ?? z;
  return izlaz;
}

const U_CIRILICU: [string, string][] = [
  ['Lj', 'Љ'], ['LJ', 'Љ'], ['lj', 'љ'], ['Nj', 'Њ'], ['NJ', 'Њ'], ['nj', 'њ'], ['Dž', 'Џ'], ['DŽ', 'Џ'], ['dž', 'џ'],
  ['A', 'А'], ['B', 'Б'], ['V', 'В'], ['G', 'Г'], ['D', 'Д'], ['Đ', 'Ђ'], ['E', 'Е'], ['Ž', 'Ж'], ['Z', 'З'], ['I', 'И'],
  ['J', 'Ј'], ['K', 'К'], ['L', 'Л'], ['M', 'М'], ['N', 'Н'], ['O', 'О'], ['P', 'П'], ['R', 'Р'], ['S', 'С'], ['T', 'Т'],
  ['Ć', 'Ћ'], ['U', 'У'], ['F', 'Ф'], ['H', 'Х'], ['C', 'Ц'], ['Č', 'Ч'], ['Š', 'Ш'],
  ['a', 'а'], ['b', 'б'], ['v', 'в'], ['g', 'г'], ['d', 'д'], ['đ', 'ђ'], ['e', 'е'], ['ž', 'ж'], ['z', 'з'], ['i', 'и'],
  ['j', 'ј'], ['k', 'к'], ['l', 'л'], ['m', 'м'], ['n', 'н'], ['o', 'о'], ['p', 'п'], ['r', 'р'], ['s', 'с'], ['t', 'т'],
  ['ć', 'ћ'], ['u', 'у'], ['f', 'ф'], ['h', 'х'], ['c', 'ц'], ['č', 'ч'], ['š', 'ш'],
];

/**
 * Латиница → ћирилица (нпр. за упит у претрази откуцан латиницом).
 * Двословна слова (lj, nj, dž) се увек спајају; ретки изузеци (нпр. „nadživeti“) треба ручно проверити.
 */
export function uCirilicu(tekst: string): string {
  let izlaz = '';
  let i = 0;
  while (i < tekst.length) {
    const dva = tekst.slice(i, i + 2);
    const par = U_CIRILICU.find(([l]) => l.length === 2 && l === dva);
    if (par) {
      izlaz += par[1];
      i += 2;
      continue;
    }
    const jedno = U_CIRILICU.find(([l]) => l === tekst[i]);
    izlaz += jedno ? jedno[1] : tekst[i];
    i += 1;
  }
  return izlaz;
}
